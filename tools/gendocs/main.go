// Command gendocs writes docs/rules.md from the rule table in the server
// package. With -check it fails when the file is out of date instead.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"strings"

	"github.com/akquisio-dev/vigil/internal/server"
)

var areas = []struct{ prefix, title string }{
	{"ssh.", "SSH access"},
	{"user.", "Accounts"},
	{"file.", "Persistence and configuration files"},
	{"port.", "Exposure"},
	{"canary.", "Canaries"},
	{"", "Integrity of vigil itself"},
}

func area(id string) int {
	for i, a := range areas[:len(areas)-1] {
		if strings.HasPrefix(id, a.prefix) {
			return i
		}
	}
	return len(areas) - 1
}

func technique(t string) string {
	if t == "" {
		return ""
	}
	return fmt.Sprintf("[%s](https://attack.mitre.org/techniques/%s/)", t, strings.ReplaceAll(t, ".", "/"))
}

func render() []byte {
	rules := server.Catalog()
	var b bytes.Buffer
	b.WriteString("<!-- Generated by `go run ./tools/gendocs` from internal/server/rules.go and rules_doc.go. Do not edit by hand. -->\n\n")
	b.WriteString("# Detection rules\n\n")
	fmt.Fprintf(&b, "vigil ships %d rules. Every alert carries the rule id, so an alert can be looked up here.\n\n", len(rules))
	b.WriteString("Severity decides who is woken up: each notifier has a `min_severity`, `high` by default.\n\n")
	b.WriteString("| Rule | Severity | ATT&CK |\n|---|---|---|\n")
	for _, r := range rules {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s | %s |\n", r.ID, anchor(r.ID), r.Severity, technique(r.Technique))
	}
	for i, a := range areas {
		fmt.Fprintf(&b, "\n## %s\n", a.title)
		for _, r := range rules {
			if area(r.ID) != i {
				continue
			}
			fmt.Fprintf(&b, "\n### `%s` {#%s}\n\n", r.ID, anchor(r.ID))
			fmt.Fprintf(&b, "**Severity:** %s", r.Severity)
			if r.Technique != "" {
				fmt.Fprintf(&b, " · **ATT&CK:** %s", technique(r.Technique))
			}
			fmt.Fprintf(&b, "\n\n**Alert:** `%s`\n\n", r.Title)
			fmt.Fprintf(&b, "**Fires when:** %s\n\n", r.Trigger)
			fmt.Fprintf(&b, "**Known false positives:** %s\n\n", r.FalsePositives)
			fmt.Fprintf(&b, "**What to do:** %s\n", r.Response)
		}
	}
	return b.Bytes()
}

func anchor(id string) string { return strings.ReplaceAll(id, ".", "-") }

func main() {
	out := flag.String("out", "docs/rules.md", "output file")
	check := flag.Bool("check", false, "fail if the file is out of date")
	flag.Parse()
	want := render()
	if *check {
		have, _ := os.ReadFile(*out)
		if !bytes.Equal(have, want) {
			log.Fatalf("%s is out of date, run: go run ./tools/gendocs", *out)
		}
		return
	}
	if err := os.WriteFile(*out, want, 0o644); err != nil {
		log.Fatal(err)
	}
}
